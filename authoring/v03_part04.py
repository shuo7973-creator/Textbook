    portfolio_variance(.5,s1,s2,rho)
    denominator=s1*s1+s2*s2-2*rho*s1*s2
    if denominator<=0:
        raise ValueError('不存在唯一最小方差权重')
    w=(s2*s2-rho*s1*s2)/denominator
