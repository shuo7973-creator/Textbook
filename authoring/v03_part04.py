def portfolio_variance(w,s1,s2,rho):
    if any(not isfinite(x) for x in (w,s1,s2,rho)) or min(s1,s2)<0 or not -1<=rho<=1:
        raise ValueError('波动非负，相关在−1至1，参数有限')
    return max(0,w*w*s1*s1+(1-w)**2*s2*s2+2*w*(1-w)*rho*s1*s2)

